const svg = (name, attrs = {}) => {
    const node = ICONS[name];
    if (!node) {
        if (import.meta.env.DEV) console.warn(`Unknown icon "${name}"`);
        return null;
    }
    return createElement(node, { 'stroke-width': 1.75, 'aria-hidden': 'true', ...attrs });
};

/** SVG markup for use in x-html / HTML strings. */
export const icon = (name, cls = 'size-4') => svg(name, { class: cls })?.outerHTML ?? '';

export function renderIcons(root = document) {
    root.querySelectorAll('i[data-icon]').forEach((el) => {
        const attrs = Object.fromEntries([...el.attributes].filter((a) => a.name !== 'data-icon').map((a) => [a.name, a.value]));
        const node = svg(el.dataset.icon, attrs);
        if (node) el.replaceWith(node);
    });
}

/** Keeps replacing placeholders that Alpine or fetched HTML add later. */
export function watchIcons() {
    renderIcons();
    let queued = false;
    new MutationObserver((mutations) => {
        if (queued || !mutations.some((m) => [...m.addedNodes].some((n) => n.nodeType === 1 && (n.matches('i[data-icon]') || n.querySelector('i[data-icon]'))))) return;
        queued = true;
        queueMicrotask(() => { queued = false; renderIcons(); });
    }).observe(document.body, { childList: true, subtree: true });
}
